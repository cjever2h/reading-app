export function genreGuide(genre, custom = {}) {
  const base = GENRE_GUIDE[genre];
  if (!base) return null;
  const cg = (custom.genreGuide || {})[genre] || {};
  const lens = cg.lens || base.lens;
  const prompts = cg.prompts && cg.prompts.length ? cg.prompts : base.prompts;
  return { ...base, lens, prompts };
}
export function genrePrompt(genre, custom = {}) { return genreGuide(genre, custom)?.lens || ''; }
